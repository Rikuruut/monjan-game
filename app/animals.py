"""動物の一覧。

プロトタイプでは10種類に絞り、スマホのプルダウンに出す。
(2026年10月30日:依頼者の指定で、鷹・ワニ・ゴリラ、サメ・ティラノサウルスを足して10種類にした)
製品版ではユーザーが自由に入力できるようにする予定なので、
動物名は「一覧の中の値」ではなく「任意の文字列」として扱えるようにしておく。
"""

ANIMALS: list[str] = [
    "ライオン",
    "ゾウ",
    "ウサギ",
    "ペンギン",
    "ネコ",
    "鷹",
    "ワニ",
    "ゴリラ",
    "サメ",
    "ティラノサウルス",
]

# 動物ごとのアイコン(PC画面の「とどいたもの」で、写真 × 動物 を見せるのに使う)
# 一覧にない動物(製品版の自由入力)は DEFAULT_ANIMAL_ICON にする
ANIMAL_ICONS: dict[str, str] = {
    "ライオン": "🦁",
    "ゾウ": "🐘",
    "ウサギ": "🐰",
    "ペンギン": "🐧",
    "ネコ": "🐱",
    "鷹": "🦅",
    "ワニ": "🐊",
    "ゴリラ": "🦍",
    "サメ": "🦈",
    "ティラノサウルス": "🦖",
}
DEFAULT_ANIMAL_ICON = "🐾"

# 動物名が空だったときに使う値
DEFAULT_ANIMAL = ANIMALS[0]

# 動物名の長さの上限(製品版の自由入力を見越した安全策)
MAX_ANIMAL_LENGTH = 20


def normalize_animal(name: str | None) -> str:
    """送られてきた動物名を整える。

    一覧に無い名前でもそのまま通す(製品版の自由入力に備える)。
    空のときだけ既定の動物にし、長すぎるときは切り詰める。
    """
    cleaned = (name or "").strip()
    if not cleaned:
        return DEFAULT_ANIMAL
    return cleaned[:MAX_ANIMAL_LENGTH]
