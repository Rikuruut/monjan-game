#
# ※ 方針
#   - 単語を2つ並べるだけにせず、音を混ぜて1つの言葉にする
#   - がっかりする名前(悪口・下品・言いにくい・実在のキャラクターや商品)を避ける。
#     プログラム側(validator.check_monster_name)でも、カタカナだけか・長さ・NGの言葉をチェックする
#   - 候補を3つ、それぞれ違う作り方で考えさせ、プログラムが良いものの中からランダムに1つ選ぶ(個性を出すため)
