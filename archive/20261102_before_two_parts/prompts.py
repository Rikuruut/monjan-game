# 一覧にない動物で選ぶパターン(シルエット型は入れない)
DEFAULT_FUSION_PART_KEYS: list[str] = ["jaw", "tail", "back", "head", "arm", "armor"]


def fusion_part_candidates(animal: str) -> list[str]:
    """その動物で使うパターンの一覧を返す。一覧にない動物は DEFAULT_FUSION_PART_KEYS。"""
    parts = ANIMAL_FUSION_PARTS.get((animal or "").strip())
    return list(parts) if parts else list(DEFAULT_FUSION_PART_KEYS)


def fusion_part_place(animal: str, part: str | None) -> str:
    """パターンの場所の言葉を返す。動物ごとの言いかえがあればそれを使う。不明なパターンなら空文字。"""
    info = FUSION_PARTS.get(part or "")
    if not info:
        return ""
    override = ANIMAL_FUSION_PARTS.get((animal or "").strip(), {}).get(part)
    return override or info["place"]


