# ----------------------------------------------------------------------
# ※ 2026年10月31日:名前は子供が最初に目にする「当たり外れ」なので、しっかり組んだ。
#   それまでは「動物と物の名前を組み合わせたカタカナ」の4行だけで、
#   同じ組み合わせだと同じ名前になりやすかった(ティラノサウルス×はさみは5回中3回が「ハサミラノ」)。
