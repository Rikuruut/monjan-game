#   実際の名前の多くが「頭を2文字ずつ切ってつなげただけ」(タカサミ・ゴリバサミ・ウサケイ)で、
#   「かいじゅうの おもちゃ」の飾りことばまで使う(カイネコ)などしていた。そこで、
#   - 考える手順(材料の音を集める → 重なる音を探す → 強い響きに整える → 声に出して確かめる)を書いた
#   - 物は英語や動き・音の言葉に言いかえてもよいことにした(はさみ → シザー・チョキ など)
#   - 3つの作り方(重ね合わせ / 言いかえ合体 / 怪獣ネーム)を1つずつ使い、良い順に並べさせる。
#     当初の3つ目「特徴ネーム」(取り込む場所の言葉も入れる)は、ライハサテイル・テプヨロイザメのように
#     体の部位を足しただけの長い名前になったので、語尾で怪獣らしくする作り方に変えた。
#     さらに、片方の材料だけに語尾をつける名前(ハサミドン・ウサギドン)が出たので、両方の音をまぜてから語尾をつけると書いた
#     プログラムは、並び順に 50% / 30% / 20% の重みで選ぶ(validator.choose_monster_name)
#   - 例は、写されないよう、動物の一覧にない組み合わせ(クジラ・せんぷうき)にした
