# 背景の場所(短いプロンプト用。毎回ランダムに1つ選ぶ)
# ----------------------------------------------------------------------
# ※ 2026年11月2日:どのカードも同じに見えたので足した。
#   ポーズ・視点・表情は毎回ちがうものが選ばれ、絵にも出ていたが、背景を画像モデルにまかせていたため、
#   どの絵も「昼の青空・白い雲・岩の地面・飛び散る岩・遠くの岩山」になっていた(STAGING_OPTIONS のコメントと同じ現象)。
#   絵の印象は背景の場所と時間帯(色)で大きく変わるので、取り込む場所と同じく1行だけ足す。
#   書くのは「時間帯・天気の場所」の2語だけ(例:月夜の森)。複雑な指示を足すと、物の取り込みが不正確になったため。
#   場所は、依頼者の基本「背景はモンスターに合うもの」に合わせて、動物のすみかから選ぶ。
#   時間帯・天気は STAGING_OPTIONS["scene"] から選ぶ。
#   町・建物は入れない(看板などの文字が描かれやすいため)。
BACKGROUND_PLACES: dict[str, list[str]] = {
    "ライオン":         ["サバンナ", "岩山", "草原"],
    "ゾウ":             ["サバンナ", "ジャングル", "川辺"],
    "ウサギ":           ["花畑", "森", "草原"],
    "ペンギン":         ["氷の大地", "雪原", "海辺"],
    "ネコ":             ["森", "花畑", "丘の上"],
    "鷹":               ["山の頂上", "雲の上", "崖"],
    "ワニ":             ["沼地", "ジャングル", "川辺"],
    "ゴリラ":           ["ジャングル", "森", "岩山"],
    "サメ":             ["海の中", "岩礁", "荒れた海"],
    "ティラノサウルス": ["火山", "ジャングル", "岩山"],
}

# 一覧にない動物(製品版の自由入力)で選ぶ場所
DEFAULT_BACKGROUND_PLACES: list[str] = ["森", "草原", "山", "空の上"]


def background_place_candidates(animal: str) -> list[str]:
    """その動物で使う背景の場所の一覧を返す。一覧にない動物は DEFAULT_BACKGROUND_PLACES。"""
    return list(BACKGROUND_PLACES.get((animal or "").strip()) or DEFAULT_BACKGROUND_PLACES)


def background_text(scene: str | None, place: str | None) -> str:
    """背景の2語(例:月夜の森)。場所がなければ空文字(背景の行を入れない)。"""
    if not place:
        return ""
    return f"{scene}の{place}" if scene else place


# 画像プロンプトの書き方(.env の IMAGE_PROMPT_STYLE)
#   detailed:設計図つきの詳しいプロンプト(IMAGE_PROMPT_TEMPLATE)
#   simple  :Playground と同じ短いプロンプト(SIMPLE_IMAGE_PROMPT_TEMPLATE)
IMAGE_PROMPT_STYLES = ("detailed", "simple")
DEFAULT_IMAGE_PROMPT_STYLE = "detailed"


def normalize_image_prompt_style(style: str | None) -> str:
    """画像プロンプトの書き方を detailed / simple のどちらかにそろえる。不明な値なら既定値にする。"""
    value = (style or "").strip().lower()
    return value if value in IMAGE_PROMPT_STYLES else DEFAULT_IMAGE_PROMPT_STYLE


# 人モードのときに、画像プロンプトへ差し込むブロック
# ※ 同意が取れている撮影でだけ使うこと。
#   OpenAIの画像モデルは実在の人物の扱いに制限があるため、
#   コンテンツフィルターで拒否されることがある(その場合はエラーをそのまま表示する)。
PERSON_IMAGE_SECTION = """## 写真に人が写っている場合
参考写真には人が写っている。この人を、物の代わりの素材として融合させる。
顔立ち・髪型・髪の色・めがね・帽子・服の色など、本人だと分かる見た目の特徴を、モンスターの顔や体に取り込む。
人の体をそのまま描かず、あくまで動物と融合したモンスターにする。本人が見て「自分がモンスターになった!」とうれしくなる、かっこいい・かわいい仕上がりにする。
体型や肌の色を強調したり、からかうような描き方にしたりしない。写真の人以外の、通りすがりの人は描かない。

"""


# 融合デザインが取れなかったときに使う値(validator.py で補う)
DEFAULT_DESIGN_PLAN: dict[str, str] = {
    "animal_identity": "その動物本来の顔つきと骨格。脚・しっぽの数と足先の形はそのまま",
    "primary_fusion": "物のいちばん目立つ形を、大きく変形して体の一部に取り込む",
    "secondary_fusion": "物の色や模様を、体の別の部位に控えめに取り込む",
    "ability": "物の使い方をもとにした ふしぎな力を、攻撃エフェクトとして放つ",
    "pose": "やや低い視点で、前に踏み出す躍動的な構え",
    "background": "その動物のすみかと、物の使われ方を組み合わせた幻想的な景色",
}


def build_image_prompt(
    animal: str,
    object_name: str,
    element: str,
    design_plan: dict[str, str] | None = None,
    allow_person: bool = False,
    has_person: bool = False,
    prompt_style: str | None = None,
) -> str:
    """画像生成プロンプトを組み立てる。

    `prompt_style` が "simple" のときは、Playground と同じ短いプロンプトを使う
    (動物名・物の名前・人モードの節だけを差し込む)。それ以外は設計図つきの詳しいプロンプト。

    動物名は製品版で自由入力になる予定なので、一覧に無い名前でもそのまま埋め込む。
    `design_plan` は判定で決めた融合の設計図(DEFAULT_DESIGN_PLAN と同じ6項目)。
    空や欠けている項目は既定値で補う。
    `element`(性質)は、いまのテンプレートには差し込み口がないので使われない。
    人の扱いの節は、人モード(`allow_person`)で、かつ判定で人が写っていた(`has_person`)ときだけ入れる。
    """
    person_section = PERSON_IMAGE_SECTION if (allow_person and has_person) else ""

    if normalize_image_prompt_style(prompt_style) == "simple":
        # 取り込む場所(判定のときに recognizer.py で選び、design_plan に入れてある)
        place = fusion_part_place(animal, (design_plan or {}).get("fusion_part"))
        # ※ 2026年11月2日:「{物}の特徴は、主に「{場所}」に取り入れて」から言い方を変えた。
        #   「取り入れて」があいまいで、本物のはさみをそのまま口にくわえる・頭に刺さる・口の前に重なる絵になった
        #   (「口・あご」で作った5回すべて)。部位そのものが物に作り変わったように描かせ、体と同じ塗り方でつなげる。
        #   失敗の型は名前だけ挙げ、描き方の具体例は書かない(例を書くと、そのまま写されるため)。行は増やさない
        # ※ 同じ日:言いかえだけでは直らなかった(4回中、製品まるごとが3回・持ち手が突き出したのが1回)。
        #   物の全体ではなく、すぐ要る判定で答えてもらった「いちばん特徴的なパーツ」だけを使わせる。
        #   パーツが分からないとき(詳しいプロンプト・判定の答えが空)は、物の全体で書く
        object_part = ((design_plan or {}).get("object_part") or "").strip()
        if place and object_part:
            fusion_part_line = (
                f"「{place}」そのものが、{object_name}の「{object_part}」に作り変わったように描いて。"
                f"{object_name}の全体ではなく「{object_part}」だけを使い、形と色は残して、体と同じ塗り方で体につなげる"
                "(くわえる・持つ・刺さる・上に重ねるのはしない。その動物にない部位なら、近い部位でよい)。\n"
            )
        elif place:
            fusion_part_line = (
                f"「{place}」そのものが、{object_name}に作り変わったように描いて。"
                f"{object_name}だと分かる形と色は残し、体と同じ塗り方で体につなげる"
                "(くわえる・持つ・刺さる・上に重ねるのはしない。その動物にない部位なら、近い部位でよい)。\n"
            )
        else:
            fusion_part_line = ""
        # ポーズ・視点・表情(判定のときに recognizer.py で選び、design_plan["staging"] に入れてある)。
        # 短いプロンプトだけだと、ポーズが毎回似た構えになったので、取り込む場所と同じく1行だけ足す。
        staging = (design_plan or {}).get("staging") or {}
        pose_parts = [
            f"{label}は「{staging[key]}」"
            for key, label in (("pose", "ポーズ"), ("view", "視点"), ("expression", "表情"))
            if staging.get(key)
        ]
        pose_line = (
            "、".join(pose_parts) + "で描いて(その動物に無理な姿勢なら、近い姿勢でよい)。\n"
            if pose_parts else ""
        )
        # 背景(場所と時間帯・天気の2語だけ。景色の中身は画像モデルにまかせる。BACKGROUND_PLACES のコメント参照)
        background = background_text(staging.get("scene"), (design_plan or {}).get("background_place"))
        background_line = (
            f"背景は「{background}」(合わなければ、近い景色でよい)。\n" if background else ""
        )
        return SIMPLE_IMAGE_PROMPT_TEMPLATE.format(
            animal=animal,
            object_name=object_name,
            fusion_part_line=fusion_part_line,
            pose_line=pose_line,
            background_line=background_line,
            person_section=person_section,
        )

    plan = dict(DEFAULT_DESIGN_PLAN)
    for key, value in (design_plan or {}).items():
        if key in plan and isinstance(value, str) and value.strip():
            plan[key] = value.strip()

    # 融合の型は判定(recognizer.py)で選んで design_plan に入れてある
    fusion_info = FUSION_TYPES.get((design_plan or {}).get("fusion_type") or "")

    return IMAGE_PROMPT_TEMPLATE.format(
        animal=animal,
        object_name=object_name,
        fusion_type_label=fusion_info["label"] if fusion_info else "おまかせ",
        staging_text=format_staging((design_plan or {}).get("staging")) or "おまかせ",
        animal_identity=plan["animal_identity"],
        primary_fusion=plan["primary_fusion"],
        secondary_fusion=plan["secondary_fusion"],
        ability=plan["ability"],
        pose=plan["pose"],
        background=plan["background"],
        person_section=person_section,
    )
