DEFAULT_DESIGN_PLAN: dict[str, str] = {
    "animal_body": "その生き物本来の脚・翼・ひれ・しっぽの数と形のまま",
}

# 置き換え対応表(parts_mapping)の件数の上限と、取れなかったときの既定値
MAX_PARTS_MAPPING = 3
DEFAULT_PARTS_MAPPING: list[dict[str, str]] = [
    {"object_part": "物の特徴的な形", "shape": "", "body_part": "体の装甲や模様"},
]


def format_parts_mapping(parts_mapping: list[dict[str, str]] | None) -> str:
    """置き換え対応表を、画像プロンプトに入れる箇条書きにする。

    例:「- 持ち手の黒い輪 → たてがみの両側の飾り」
    """
    rows = []
    for item in parts_mapping or []:
        if not isinstance(item, dict):
            continue
        obj = (item.get("object_part") or "").strip()
        body = (item.get("body_part") or "").strip()
        if obj and body:
            rows.append(f"- {obj} → {body}")
    if not rows:
        rows = [f"- {d['object_part']} → {d['body_part']}" for d in DEFAULT_PARTS_MAPPING]
    return "\n".join(rows[:MAX_PARTS_MAPPING])


def build_image_prompt(
    animal: str,
    object_name: str,
    element: str,
    design_plan: dict[str, str] | None = None,
    allow_person: bool = False,
    fusion_mode: str | None = None,
) -> str:
    """画像生成プロンプトを組み立てる。

    動物名は製品版で自由入力になる予定なので、一覧に無い名前でもそのまま埋め込む。
    `design_plan` の2項目を差し込む。
      - parts_mapping(置き換え対応表)→【融合のやり方】に差し込む
      - animal_body(生き物本来の体のつくり)→【体のつくり】に差し込む
    `element`(性質)は、いまのテンプレートには差し込み口がないので使われない。
    あとでテンプレートに {element} を書き足せば、そのまま効くようにしてある。
    (str.format は余分なキーワード引数を無視するため、このままで問題ない)
    `fusion_mode` で、融合のやり方(控えめ calm / 派手 bold)を切り替える。
    """
    mode = normalize_fusion_mode(fusion_mode)
    design_plan = design_plan or {}
    plan = dict(DEFAULT_DESIGN_PLAN)
    for key, value in design_plan.items():
        if key in plan and isinstance(value, str) and value.strip():
            plan[key] = value.strip()

    return IMAGE_PROMPT_TEMPLATE.format(
        animal=animal,
        object_name=object_name,
        person_section=PERSON_IMAGE_SECTION if allow_person else "",
        fusion_section=FUSION_SECTIONS[mode].format(
            parts_mapping_text=format_parts_mapping(design_plan.get("parts_mapping")),
        ),
        fusion_conditions=FUSION_CONDITIONS[mode],
        element=element,
        element_light_color=ELEMENT_LIGHT_COLORS.get(element, DEFAULT_LIGHT_COLOR),
        animal_body=plan["animal_body"],
    )
