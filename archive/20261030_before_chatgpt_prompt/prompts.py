def normalize_fusion_mode(mode: str | None) -> str:
    """融合の強さを calm / bold のどちらかにそろえる。不明な値なら既定値にする。"""
    value = (mode or "").strip().lower()
    return value if value in FUSION_MODES else DEFAULT_FUSION_MODE


def build_recognize_instructions(allow_person: bool = False, fusion_mode: str | None = None) -> str:
    """判定モデルに渡す指示文を組み立てる。

    `allow_person` が true のときは、人が写っていても撮り直しにしない。
    `fusion_mode` で、置き換え対応表の作り方(控えめ / 派手)を切り替える。
    """
    text = RECOGNIZE_INSTRUCTIONS + PARTS_RULES[normalize_fusion_mode(fusion_mode)]
    if allow_person:
        text += PERSON_MODE_RECOGNIZE_NOTE
    return text


def build_recognize_prompt(animal: str) -> str:
    """判定のときにユーザー発言として渡す文を作る。"""
    return (
        f"子供が選んだ動物は「{animal}」です。\n"
        f"添付した写真に写っている物を見て、「{animal}」と合体したモンスターの情報を作ってください。\n"
        f"融合デザイン(design_plan)は、このあと画像を描くための設計図として使います。"
    )


