# ※ 原文は Markdown の見出し(##)を使っているので、そのまま残している。
#   人モードのときは、【融合の原則】のあとに人の扱いのブロックを足す({person_section})。
#
# ※ 性質(element)は、このテンプレートでは使っていない。
#   判定では引き続き出力し、result.json に保存している(じゃんけんバトル用)。
IMAGE_PROMPT_TEMPLATE = """# モンじゃん!画像生成プロンプト

## 役割
動物と身近な物を融合させ、独創的で迫力のあるオリジナルモンスターをデザインする。

## 融合設計
以下の設計データを最優先して反映する。

- 動物:{animal_identity}
- 物:{object_name}
- メインの融合:{primary_fusion}
- サブの融合:{secondary_fusion}
- 能力:{ability}
- ポーズ:{pose}
- 背景:{background}

## 融合の原則
動物と物を単純に並べたり、物をそのまま貼り付けたりしない。物の形状・素材・構造を大胆に変形し、動物の体の一部として成立させる。

融合部分は、動物の骨格や筋肉、体表の形状に沿って自然につなげる。物の特徴は指定された融合部位を中心に表現し、同じパーツを全身に繰り返さない。

動物本来の顔つきと基本的な骨格を維持し、元の動物が明確に分かるようにする。余分な頭・手足・指・爪・しっぽは追加しない。手足や指先を物で置き換えず、物を手に持たせない(ただし、融合設計で前足を武器にすると指定された場合は、下の「手足を武器にする場合」に従う)。

能力は体そのものに無関係なパーツを追加するのではなく、攻撃エフェクトとして表現する。

## 手足を武器にする場合
手足を武器にしてよいが、次の条件を守る。
- 武器にするのは前足(腕)の1対だけ。後ろ足は普通の足のままにする
- 手首から先を武器にし、手首より上は動物本来の腕のままにする
- 武器の数は指定された数だけ描く(例:左右に1つずつ、合計2つ)
- 手足の本数は動物本来の数のままにする
- 四本足の動物は、武器にした前足でも地面に立てる形にする
  (例:刃の峰の部分で地面を踏みしめる)

## わくわく感
小学生・中学生が見て「かっこいい!強そう!」とわくわくする、カードの当たりのような特別感のある一枚にする。

- 能力に書いた必殺技を、まさに放っている瞬間を切り取る。止まって立っているだけの絵にしない
- 必殺技のエフェクトを、モンスターと並ぶ画面の主役として大きく描く
- 融合した部分は大きく誇張し、シルエットだけで強そうと分かるようにする
- 目に強い光を入れ、気合いの入った表情にする
- 逆光や輪郭の光(リムライト)で、モンスターのシルエットを際立たせる

{person_section}## 画風
太く強弱のある手描き風の輪郭線、2〜3段階のセル塗り、明確なシルエット、強いハイライトとコントラスト。かわいさ40%、かっこよさ60%。子供が楽しめる迫力を持たせ、過度に恐ろしくしない。

金属や装甲はマットな質感を基本とし、過剰なグラデーションや細かな装飾を避ける。エフェクトは大きな流れを1〜2本に絞る。

## 構図・背景
モンスターの全身が分かる、やや低い視点の躍動的な構図。上下左右に適度な余白を残す。

背景は融合した動物の生息環境と物の用途・特徴を組み合わせた幻想的な景色にする。背景の描き込みは控えめにし、モンスターを最も目立たせる。地面のひび割れ、砕けた岩、砂ぼこりは描かない。

## 禁止事項
文字、数字、ロゴ、署名、透かしを描かない。物の特徴を指定されていない部位に増殖させない。既存作品のキャラクターやデザインを模倣しない。
"""

# 人モードのときに、画像プロンプトへ差し込むブロック
# ※ 同意が取れている撮影でだけ使うこと。
#   OpenAIの画像モデルは実在の人物の扱いに制限があるため、
#   コンテンツフィルターで拒否されることがある(その場合はエラーをそのまま表示する)。
PERSON_IMAGE_SECTION = """## 写真に人が写っている場合
参考写真には人が写っている。この人を、物の代わりの素材として融合させる。
顔立ち・髪型・髪の色・めがね・帽子・服の色など、本人だと分かる見た目の特徴を、モンスターの顔や体に取り込む。
人の体をそのまま描かず、あくまで動物と融合したモンスターにする。本人が見て「自分がモンスターになった!」とうれしくなる、かっこいい・かわいい仕上がりにする。
体型や肌の色を強調したり、からかうような描き方にしたりしない。写真の人以外の、通りすがりの人は描かない。

"""


# 融合デザインが取れなかったときに使う値(validator.py で補う)
DEFAULT_DESIGN_PLAN: dict[str, str] = {
    "animal_identity": "その動物本来の顔つきと骨格。脚・しっぽの数と足先の形はそのまま",
    "primary_fusion": "物のいちばん目立つ形を、大きく変形して体の一部に取り込む",
    "secondary_fusion": "物の色や模様を、体の別の部位に控えめに取り込む",
    "ability": "物の使い方をもとにした ふしぎな力を、攻撃エフェクトとして放つ",
    "pose": "やや低い視点で、前に踏み出す躍動的な構え",
    "background": "その動物のすみかと、物の使われ方を組み合わせた幻想的な景色",
}


def build_image_prompt(
    animal: str,
    object_name: str,
    element: str,
    design_plan: dict[str, str] | None = None,
    allow_person: bool = False,
    has_person: bool = False,
) -> str:
    """画像生成プロンプトを組み立てる。

    動物名は製品版で自由入力になる予定なので、一覧に無い名前でもそのまま埋め込む。
    `design_plan` は判定で決めた融合デザイン(DEFAULT_DESIGN_PLAN と同じ6項目)。
    空や欠けている項目は既定値で補う。
    `element`(性質)は、いまのテンプレートには差し込み口がないので使われない。
    人の扱いの節は、人モード(`allow_person`)で、かつ判定で人が写っていた(`has_person`)ときだけ入れる。
    (以前は人モードなら必ず入れていたため、物の写真でもメガネなどが描かれてしまった)
    """
    plan = dict(DEFAULT_DESIGN_PLAN)
    for key, value in (design_plan or {}).items():
        if key in plan and isinstance(value, str) and value.strip():
            plan[key] = value.strip()

    return IMAGE_PROMPT_TEMPLATE.format(
        # 動物名が抜けないように、名前と特徴を並べる
        animal_identity=f"{animal}({plan['animal_identity']})",
        object_name=object_name,
        primary_fusion=plan["primary_fusion"],
        secondary_fusion=plan["secondary_fusion"],
        ability=plan["ability"],
        pose=plan["pose"],
        background=plan["background"],
        person_section=PERSON_IMAGE_SECTION if (allow_person and has_person) else "",
    )
