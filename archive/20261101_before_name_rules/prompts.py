# ----------------------------------------------------------------------
# 物を取り込む場所のパターン(短いプロンプト用。毎回ランダムに1つ選ぶ)
# ----------------------------------------------------------------------
# ※ 2026年10月30日:短いプロンプトでは、取り込む場所を画像モデルが毎回いちばんありがちな所に決めてしまい、
