# ----------------------------------------------------------------------
# 判定と同じ NAME_RULES を使うので、ここで良い名前が出れば、判定でも同じように出るはず。
# ただし判定は写真を見ているので、写真の色や形から名前のヒントを得ることもある(テストでは物の名前だけ)。
NAME_TEST_INSTRUCTIONS = f"""あなたは、子供向けのゲーム「モンじゃん!」で、モンスターの名前をつける係です。
子供が選んだ「動物」と、子供が撮った「身の回りの物」が合体したモンスターの名前を考えます。

{NAME_RULES}"""


def build_name_test_prompt(animal: str, object_name: str, fusion_place: str | None = None) -> str:
    """名前のテストで、ユーザー発言として渡す文を作る。"""
    text = (
        f"動物は「{animal}」、物は「{object_name}」です。\n"
        f"この2つが合体したモンスターの名前の候補を、name_candidates に3つ書いてください。"
    )
    if fusion_place:
        text += f"\n物の特徴は、主に「{fusion_place}」に取り込まれる予定です。名前のヒントにしてかまいません。"
    return text


def _append_recognize_options(text: str, fusion_type: str | None, staging: dict[str, str] | None) -> str:
    """判定の依頼文に、融合の型と演出の指定を足す(詳しいプロンプト用)。"""
    info = FUSION_TYPES.get(fusion_type or "")
    if info:
        text += f"\n\n今回の融合の型は「{info['label']}」です。{info['guide']}"
    staging_text = format_staging(staging)
    if staging_text:
        text += (
            f"\n\n今回の演出は「{staging_text}」です。"
            "pose はこのポーズ・視点・表情の方向で、background はこの時間帯・天気で書いてください。"
            "動物や融合の型に合わない場合は、近いものに変えてかまいません。"
        )
    return text


